client = genai.Client()

_WINNER_SCHEMA = {
    "type": "object",
    "properties": {
        "winner": {"type": "string", "enum": ["A", "B", "tie"]},
    },
    "required": ["winner"],
}


def _score_schema(verbose: bool = False) -> dict:
    properties = {"score": {"type": "integer"}}
    required = ["score"]
    if verbose:
        properties["reason"] = {"type": "string"}
        required.append("reason")
    return {"type": "object", "properties": properties, "required": required}


def _judge_generate_config(
    response_schema: dict,
    *,
    temperature: float = 0.0,
    max_output_tokens: int = 256,
) -> types.GenerateContentConfig:
    return types.GenerateContentConfig(
        temperature=temperature,
        max_output_tokens=max_output_tokens,
        response_mime_type="application/json",
        response_schema=response_schema,
        thinking_config=types.ThinkingConfig(thinking_budget=0),
    )


def extract_json(text):
    """
    Robust JSON extraction from Gemini responses.
    """
    if not text or not text.strip():
        raise json.JSONDecodeError("Empty response", "", 0)

    text = text.strip()

    fence_match = re.search(r"```(?:json)?\s*([\s\S]*?)```", text)
    if fence_match:
        text = fence_match.group(1).strip()
    elif text.startswith("```"):
        text = text.replace("```json", "").replace("```", "").strip()

    start = text.find("{")
    if start == -1:
        raise json.JSONDecodeError("No JSON object found", text, 0)

    end = text.rfind("}")
    if end == -1 or end < start:
        score_match = re.search(r'"score"\s*:\s*(\d+)', text)
        if score_match:
            return {"score": int(score_match.group(1))}
        winner_match = re.search(r'"winner"\s*:\s*"(A|B|tie)"', text)
        if winner_match:
            return {"winner": winner_match.group(1)}
        raise json.JSONDecodeError("Incomplete JSON object", text, start)

    return json.loads(text[start : end + 1])


async def evaluate_completion(
        completion,
        criterion,
        prompt,
        client,
        model,
        verbose=False
):
    system_message = (
        "You score texts generated by a language model based on the following criterion:\n"
        + criterion +
        ".\nYou provide a score from 1 to 10.\n"
        "The language model was given a prompt and generated the following text.\n"
        "Evaluate the text based on the criterion.\n"
        "Output ONLY valid JSON with the following fields:\n"
        "{\"score\": int}"
    )

    if verbose:
        system_message += ', and optionally "reason"'

    prompt_user_text = f"Prompt:\n\n{prompt}\n\n" if prompt else ""

    user_message = (
        prompt_user_text +
        f'Completion:\n"""\n{completion}\n"""'
    )

    full_prompt = system_message + "\n\n" + user_message
    content = None

    try:
        response = await client.aio.models.generate_content(
            model=model,
            contents=full_prompt,
            config=_judge_generate_config(
                _score_schema(verbose),
                temperature=0.0,
            ),
        )

        content = response.text
        return extract_json(content)

    except json.JSONDecodeError as e:
        print(f"JSON decode error: {e}")
        if content is not None:
            print(f"Response content:\n{content}")

        return {
            "score": 0,
            "error": "Failed to parse JSON response"
        }

    except Exception as e:
        print(f"Error in evaluate_completion: {e}")

        return {
            "score": 0,
            "error": str(e)
        }


async def evaluate_with_timeout(
        completion,
        criterion,
        prompt,
        client,
        model,
        verbose,
        timeout
):
    try:
        return await asyncio.wait_for(
            evaluate_completion(
                completion,
                criterion,
                prompt,
                client,
                model,
                verbose
            ),
            timeout=timeout
        )

    except asyncio.TimeoutError:
        return {
            "score": 0,
            "error": "Timeout"
        }


def evaluate_completions(
        completions: list[str],
        criterion: str,
        prompt: str,
        model="models/gemini-2.5-flash",
        verbose=False,
):
    async def evaluate_all():
        tasks = [
            evaluate_completion(
                completion,
                criterion,
                prompt,
                client,
                model,
                verbose=verbose
            )
            for completion in completions
        ]

        return await asyncio.gather(*tasks)

    return asyncio.run(evaluate_all())


def multi_criterion_evaluation(
        completions: list[str],
        criterions: list[str],
        prompt: str,
        model="models/gemini-2.5-flash",
        verbose=False,
        filter_errors=True,
        print_errors=False,
        batch_size=1000,
        timeout=20,
):
    repeated_completions = completions * len(criterions)

    repeated_criteria = []

    for criterion in criterions:
        repeated_criteria.extend([criterion] * len(completions))

    async def retry_evaluate(
            completion,
            criterion,
            prompt,
            client,
            model,
            verbose,
            timeout,
            max_retries=1
    ):
        attempts = 0

        while attempts <= max_retries:
            result = await evaluate_with_timeout(
                completion,
                criterion,
                prompt,
                client,
                model,
                verbose,
                timeout
            )

            if "error" not in result:
                return result

            elif attempts == max_retries:
                return result

            elif result.get("error") in ("Timeout", "Failed to parse JSON response"):
                attempts += 1

            else:
                return result

    async def evaluate_all():
        tasks = [
            retry_evaluate(
                completion,
                criterion,
                prompt,
                client,
                model,
                verbose,
                timeout,
                max_retries=1
            )
            for completion, criterion in zip(
                repeated_completions,
                repeated_criteria
            )
        ]

        results = []

        for i in range(0, len(tasks), batch_size):
            chunk = tasks[i:i + batch_size]

            chunk_results = await asyncio.gather(*chunk)

            results.extend(chunk_results)

        return results

    results = asyncio.run(evaluate_all())

    reshaped_results = []

    for i in range(len(criterions)):
        reshaped_results.append(
            results[i * len(completions):(i + 1) * len(completions)]
        )

    if not filter_errors:
        return reshaped_results

    filtered_results = []
    error_counts = {}

    for criterion_results in reshaped_results:
        valid_criterion_results = []

        for result in criterion_results:
            if "error" not in result:
                valid_criterion_results.append(result)

            else:
                error_msg = result.get("error", "Unknown error")

                error_counts[error_msg] = (
                    error_counts.get(error_msg, 0) + 1
                )

        filtered_results.append(valid_criterion_results)

    if print_errors and error_counts:
        error_summary = ", ".join([
            f"{count} '{error_msg}' errors"
            for error_msg, count in error_counts.items()
        ])

        print(f"Errors occurred during evaluation: {error_summary}")

    return filtered_results


async def run_battle(
        text_1,
        text_2,
        criterion,
        prompt,
        client,
        model
):
    """
    For Elo rating. Evaluate two texts and return the winner.
    """

    system_message = f"""
You are an impartial judge tasked with comparing two text snippets generated by a language model.

Criterion for judgment:
{criterion}

Return ONLY valid JSON in this format:
{{
  "winner": "A"
}}

Possible values:
- "A"
- "B"
- "tie"
"""

    prompt_user_text = f"Prompt:\n\n{prompt}\n\n" if prompt else ""

    user_message = prompt_user_text + f"""
Text A:
\"\"\"
{text_1}
\"\"\"

Text B:
\"\"\"
{text_2}
\"\"\"
"""

    full_prompt = system_message + "\n\n" + user_message
    content = None

    try:
        response = await client.aio.models.generate_content(
            model=model,
            contents=full_prompt,
            config=_judge_generate_config(
                _WINNER_SCHEMA,
                temperature=0.2,
                max_output_tokens=128,
            ),
        )

        content = response.text
        result = extract_json(content)

        return result

    except json.JSONDecodeError as e:
        print(f"JSON decode error: {e}")
        if content is not None:
            print(f"Response content:\n{content}")
        else:
            print(f"Text causing the error:\n{text_1}\n{text_2}")

        return {
            "winner": "error",
            "tie": False
        }

    except Exception as e:
        print(f"Error in run_battle: {e}")

        return {
            "winner": "error",
            "tie": False
        }


def compute_battles(
        models_completions: list[list[str]],
        criterion: str,
        prompt: str,
        model="models/gemini-2.5-flash",
        batch_size=1000,
        n_iterations_per_model=50,
):
    battles = []

    for model_1 in range(len(models_completions)):
        for i in range(n_iterations_per_model):

            model_2 = random.choice(range(len(models_completions)))

            completion_1 = random.choice(
                models_completions[model_1]
            )

            completion_2 = random.choice(
                models_completions[model_2]
            )

            battles.append((
                model_1,
                model_2,
                completion_1,
                completion_2
            ))

    random.shuffle(battles)

    async def evaluate_all():
        tasks = [
            run_battle(
                text_1,
                text_2,
                criterion,
                prompt,
                client,
                model
            )
            for _, _, text_1, text_2 in battles
        ]

        chunked_tasks = [
            tasks[i:i + batch_size]
            for i in range(0, len(tasks), batch_size)
        ]

        results = []

        for chunk in chunked_tasks:
            results.extend(await asyncio.gather(*chunk))

        return results

    results = asyncio.run(evaluate_all())

    filtered_results = []

    for i, result in enumerate(results):

        result["model_1"] = battles[i][0]
        result["model_2"] = battles[i][1]

        if "error" not in result and "winner" in result:
            filtered_results.append(result)

    return filtered_results


def run_comparisons(
        text_pairs: list[tuple[str, str]],
        criterion: str,
        prompt: str,
        model="models/gemini-2.5-flash",
        batch_size=1000,
):
    async def evaluate_all():
        tasks = [
            run_battle(
                text_1,
                text_2,
                criterion,
                prompt,
                client,
                model
            )
            for text_1, text_2 in text_pairs
        ]

        chunked_tasks = [
            tasks[i:i + batch_size]
            for i in range(0, len(tasks), batch_size)
        ]

        results = []

        for chunk in chunked_tasks:
            results.extend(await asyncio.gather(*chunk))

        return results

    results = asyncio.run(evaluate_all())

    return results


