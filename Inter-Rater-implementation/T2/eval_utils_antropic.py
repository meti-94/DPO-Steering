client = AsyncAnthropic()


def _extract_json_object_with_score(content: str) -> dict[str, Any] | None:
    """
    Parse {\"score\": ...} when the model prefixes prose (JSONDecodeError at line 1).
    Tries balanced-brace slices from each '{' position, preferring the last opening brace.
    """
    brace_starts = [i for i, c in enumerate(content) if c == "{"]
    for start in reversed(brace_starts):
        depth = 0
        for end in range(start, len(content)):
            if content[end] == "{":
                depth += 1
            elif content[end] == "}":
                depth -= 1
                if depth == 0:
                    chunk = content[start : end + 1]
                    try:
                        obj = json.loads(chunk)
                    except json.JSONDecodeError:
                        break
                    if isinstance(obj, dict) and "score" in obj:
                        return obj
                    break
    return None


async def evaluate_completion(completion, criterion, prompt, client, model, verbose=False):
    system_message = (
        "You score texts generated by a language model based on the following criterion:\n"
        + criterion +
        ".\nYou provide a score from 1 to 10.\n"
        "The language model was given a prompt and generated the following text.\n"
        "Evaluate the text based on the criterion.\n"
        "Do not include any explanation or commentary.\n"
        "Output ONLY valid JSON with the following fields: "
        "{\"score\": int}"
    )

    if verbose:
        system_message += ', and optionally "reason"'

    prompt_user_text = f"Prompt:\n\n{prompt}\n\n" if prompt else ""

    user_message = (
        prompt_user_text +
        f'Completion:\n"""\n{completion}\n"""\n'
    )

    try:
        response = await client.messages.create(
            model=model,
            max_tokens=150,
            temperature=0.0,
            system=system_message,
            messages=[
                {
                    "role": "user",
                    "content": user_message
                }
            ]
        )

        content = response.content[0].text.strip()

        # Optional cleanup if Claude wraps JSON in markdown
        if content.startswith("```json"):
            content = content.replace("```json", "").replace("```", "").strip()

        try:
            return json.loads(content)
        except json.JSONDecodeError:
            recovered = _extract_json_object_with_score(content)
            if recovered is not None:
                return recovered
            raise

    except json.JSONDecodeError as e:
        print(f"JSON decode error: {e}")
        print(f"Response content:\n{content}")
        return {"score": 0, "error": "Failed to parse JSON response"}

    except Exception as e:
        print(f"Error in evaluate_completion: {e}")
        return {"score": 0, "error": str(e)}


async def evaluate_with_timeout(
    completion,
    criterion,
    prompt,
    client,
    model,
    verbose,
    timeout
):
    try:
        return await asyncio.wait_for(
            evaluate_completion(
                completion,
                criterion,
                prompt,
                client,
                model,
                verbose
            ),
            timeout=timeout
        )

    except asyncio.TimeoutError:
        return {"score": 0, "error": "Timeout"}


def evaluate_completions(
        completions: list[str],
        criterion: str,
        prompt: str,
        model="claude-haiku-4-5",
        verbose=False,
):
    async def evaluate_all():
        tasks = [
            evaluate_completion(
                completion,
                criterion,
                prompt,
                client,
                model,
                verbose=verbose
            )
            for completion in completions
        ]

        return await asyncio.gather(*tasks)

    return asyncio.run(evaluate_all())


def multi_criterion_evaluation(
        completions: list[str],
        criterions: list[str],
        prompt: str,
        model="claude-sonnet-4-20250514",
        verbose=False,
        filter_errors=True,
        print_errors=False,
        batch_size=1000,
        timeout=20,
):
    repeated_completions = completions * len(criterions)

    repeated_criteria = []
    for criterion in criterions:
        repeated_criteria.extend([criterion] * len(completions))

    async def retry_evaluate(
            completion,
            criterion,
            prompt,
            client,
            model,
            verbose,
            timeout,
            max_retries=1
    ):
        attempts = 0

        while attempts <= max_retries:
            result = await evaluate_with_timeout(
                completion,
                criterion,
                prompt,
                client,
                model,
                verbose,
                timeout
            )

            if "error" not in result:
                return result

            elif attempts == max_retries:
                return result

            elif result.get("error") == "Timeout":
                attempts += 1

            else:
                return result

    async def evaluate_all():
        tasks = [
            retry_evaluate(
                completion,
                criterion,
                prompt,
                client,
                model,
                verbose,
                timeout,
                max_retries=1
            )
            for completion, criterion in zip(
                repeated_completions,
                repeated_criteria
            )
        ]

        results = []

        for i in range(0, len(tasks), batch_size):
            chunk = tasks[i:i + batch_size]
            chunk_results = await asyncio.gather(*chunk)
            results.extend(chunk_results)

        return results

    results = asyncio.run(evaluate_all())

    reshaped_results = []

    for i in range(len(criterions)):
        reshaped_results.append(
            results[i * len(completions):(i + 1) * len(completions)]
        )

    if not filter_errors:
        return reshaped_results

    filtered_results = []
    error_counts = {}

    for criterion_results in reshaped_results:
        valid_criterion_results = []

        for result in criterion_results:
            if "error" not in result:
                valid_criterion_results.append(result)

            else:
                error_msg = result.get("error", "Unknown error")
                error_counts[error_msg] = (
                    error_counts.get(error_msg, 0) + 1
                )

        filtered_results.append(valid_criterion_results)

    if print_errors and error_counts:
        error_summary = ", ".join([
            f"{count} '{error_msg}' errors"
            for error_msg, count in error_counts.items()
        ])

        print(f"Errors occurred during evaluation: {error_summary}")

    return filtered_results